// "my" is the ending ـي. Only these common words are swapped to "your" (ـك), because many other words end in ي.
const MINE = [
  'جدتي', 'جدي', 'أمي', 'امي', 'أبي', 'ابي', 'بيتي', 'غرفتي', 'منزلي', 'حديقتي', 'قريتي', 'مدينتي', 'بلدي', 'سريري',
  'عائلتي', 'أهلي', 'اهلي', 'خالتي', 'عمتي', 'خالي', 'عمي', 'أختي', 'اختي', 'أخي', 'اخي', 'صديقي', 'صديقتي', 'طفولتي',
];

/** "حديقة جدتي" → "حديقة جدتك". */
function toYou(phrase: string): string {
  return phrase
    .split(/\s+/)
    .map((w) => (MINE.includes(w) ? `${w.slice(0, -1)}ك` : w === 'لي' ? 'لك' : w))
    .join(' ');
}

