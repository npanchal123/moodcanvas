/** "मेरी नानी का घर" → "आपकी नानी का घर". */
function toYou(phrase: string): string {
  const swaps: Record<string, string> = {
    मेरी: 'आपकी', मेरा: 'आपका', मेरे: 'आपके', मैं: 'आप', मुझे: 'आपको',
    meri: 'aapki', mera: 'aapka', mere: 'aapke',
  };
  return phrase
    .split(/\s+/)
    .map((w) => swaps[w.toLowerCase()] ?? w)
    .join(' ');
}

