/** "к моей бабушке" → "к вашей бабушке". Russian possessives change with case, so each form is swapped. */
function toYou(phrase: string): string {
  const swaps: Record<string, string> = {
    мой: 'ваш', моя: 'ваша', моё: 'ваше', мое: 'ваше', мои: 'ваши', моего: 'вашего', моей: 'вашей', моему: 'вашему',
    мою: 'вашу', моим: 'вашим', моих: 'ваших', моём: 'вашем', моем: 'вашем', моими: 'вашими', меня: 'вас', мне: 'вам',
  };
  return phrase.replace(/(?<![\p{L}])\p{L}+(?![\p{L}])/gu, (w) => swaps[w.toLowerCase()] ?? w);
}

